/**
 * Generates official exam copies for a specific exam center based on its pre-assigned, adjustable quota.
 * No student names or student tickets. Every sheet is an officially numbered exam copy for the center.
 */
export function generateCenterCopiesForSchool(school: SchoolCenter): StudentTicket[] {
  const copies: StudentTicket[] = [];
  const quota = school.examCopiesQuota || school.registeredStudentsCount || 50;

  for (let i = 1; i <= quota; i++) {
    const rawSum =
      (school.code.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0) + i * 19) % 999;
    const crc = 'C' + rawSum.toString(36).toUpperCase().padStart(3, '0');
    const code = `MOE-IRQ-2026-${school.code}-COPY-${i.toString().padStart(3, '0')}-${crc}`;

    copies.push({
      id: `CPY-${school.code}-${i}`,
      seatNumber: i, // رقم تسلسل النسخة بالمركز
      studentName: `نسخة رقم (${i}) من إجمالي (${quota})`,
      hallNumber: Math.ceil(i / 25), // القاعة التقريبية للتوزيع
      uniqueWatermarkCode: code,
      isPrinted: false,
      reprintCount: 0,
    });
  }

  return copies;
}

